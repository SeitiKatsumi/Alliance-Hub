async function fixture() {
  const db=new PGlite();
  await db.exec(`CREATE SCHEMA built_legacy;
    CREATE TABLE built_legacy.cadastro_geral(id text PRIMARY KEY,nome text,telefone text,segmento text,tags text);
    CREATE TABLE built_legacy."Comunidade"(id text PRIMARY KEY,nome text);
    CREATE TABLE built_legacy.comunidade_membros(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,comunidade_id text REFERENCES built_legacy."Comunidade",cadastro_geral_id text REFERENCES built_legacy.cadastro_geral);
    CREATE TABLE built_legacy.fluxo_caixa(id uuid DEFAULT gen_random_uuid() PRIMARY KEY,valor numeric(18,2),descricao text,data_vencimento date);
    CREATE TABLE built_legacy.directus_users(id text,email text,password text,status text,tfa_secret text,first_name text,last_name text,role text);
    INSERT INTO built_legacy.cadastro_geral VALUES ('a','Sara',null,null,'["PT"]'),('b','Bruno',null,null,'[]');
    INSERT INTO built_legacy."Comunidade" VALUES ('c','Comunidade'),('d','Outra');
    INSERT INTO built_legacy.comunidade_membros(comunidade_id,cadastro_geral_id) VALUES ('c','a'),('d','b');`);
  const columns=(await db.query<any>("SELECT table_name,column_name,udt_name FROM information_schema.columns WHERE table_schema='built_legacy'")).rows;
  const catalog:Catalog={columns,primaryKeys:[...new Set(columns.map(c=>c.table_name))].map(table_name=>({table_name,column_name:'id'})),relations:[
    {many_collection:'comunidade_membros',many_field:'comunidade_id',one_collection:'Comunidade',one_field:'membros',junction_field:'cadastro_geral_id',one_deselect_action:'nullify'},
    {many_collection:'comunidade_membros',many_field:'cadastro_geral_id',one_collection:'cadastro_geral',one_field:null,junction_field:null},
  ],fields:[{collection:'cadastro_geral',field:'tags',special:'cast-json'}]};
  return {db,catalog,store:new NativeDataStore(db,catalog)};
}
const q=(value:string)=>parseNativeQuery(new URLSearchParams(value));
test('native: filtros parametrizados, campos, aliases e expansões mantêm vínculos',async()=>{
  const {db,store}=await fixture();try{
    const rows=await store.read('Comunidade',q('fields=id,membros.cadastro_geral_id.nome&filter[membros][cadastro_geral_id][nome][_eq]=Sara'));
    assert.deepEqual(rows,[{id:'c',membros:[{cadastro_geral_id:{nome:'Sara'}}]}]);
    assert.deepEqual(await store.read('cadastro_geral',q('fields=nome&filter[nome][_eq]='+encodeURIComponent("Sara' OR 1=1 --"))),[]);
    assert.deepEqual(await store.read('cadastro_geral',q('fields=id&filter[_or][0][nome][_eq]=Sara&filter[_or][1][nome][_eq]=Bruno')),[{id:'a'},{id:'b'}]);
    assert.deepEqual((await store.read('cadastro_geral',q('fields=tags&filter[id][_eq]=a')))[0].tags,['PT']);
    assert.deepEqual(await store.project('fluxo_caixa',[{data_vencimento:new Date(2026,9,27)}],'data_vencimento'),[{data_vencimento:'2026-10-27'}]);
    await assert.rejects(store.read('directus_users',q('')),/indisponível/);
    await assert.rejects(store.read('cadastro_geral',q('sort=nome;DROP TABLE')),/Campo/);
    assert.throws(()=>q('filter[__proto__][polluted]=true'),/Filtro/);
    assert.throws(()=>q('limit=10;DELETE'),/Paginação/);
  }finally{await db.close();}
});
test('native: relacionamento não duplica, não toma vínculo alheio e gravação é reversível',async()=>{
  const {db,store}=await fixture();try{
    await db.exec('BEGIN');
    await store.save('Comunidade',{membros:[{cadastro_geral_id:'a'},{cadastro_geral_id:'b'},{cadastro_geral_id:'b'}]},'c');
    await store.save('Comunidade',{membros:[{cadastro_geral_id:'a'},{cadastro_geral_id:'b'}]},'c');
    assert.equal((await db.query("SELECT * FROM built_legacy.comunidade_membros WHERE comunidade_id='c'")).rows.length,2);
    await assert.rejects(store.save('Comunidade',{membros:[2]},'c'),/não pertence/);
    await store.save('cadastro_geral',{telefone:'+351912345678',segmento:'x'.repeat(1000)},'a');
    const cash=await store.save('fluxo_caixa',{valor:12.34,descricao:'Teste'});
    assert.equal((await store.project('fluxo_caixa',[cash],'valor'))[0].valor,12.34);
    await db.exec('ROLLBACK');
    assert.equal((await db.query<any>("SELECT telefone FROM built_legacy.cadastro_geral WHERE id='a'")).rows[0].telefone,null);
    assert.equal((await db.query('SELECT * FROM built_legacy.fluxo_caixa')).rows.length,0);
  }finally{await db.close();}
});
test('native: arquivos mantêm bytes, validam conteúdo e recusam caminho fora do armazenamento',async()=>{
  const {db,catalog}=await fixture();const root=await mkdtemp(path.join(os.tmpdir(),'built-native-files-'));
  try{
    await db.exec('CREATE TABLE built_legacy.directus_files(id uuid PRIMARY KEY,storage text,filename_disk text,filename_download text,title text,type text,filesize integer,uploaded_on timestamptz)');
    catalog.columns.push(...(await db.query<any>("SELECT table_name,column_name,udt_name FROM information_schema.columns WHERE table_schema='built_legacy' AND table_name='directus_files'")).rows);
    catalog.primaryKeys.push({table_name:'directus_files',column_name:'id'});
    const request=(p:string,init?:RequestInit)=>nativeRequest(db,catalog,new URL('https://internal.invalid'+p),init,root);
    const bytes=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a8i8AAAAASUVORK5CYII=','base64');
    const form=new FormData();form.set('file',new Blob([bytes],{type:'image/png'}),'fixture.png');
    const created=await request('/files',{method:'POST',body:form});assert.equal(created.status,200);
    const file=(await created.json()).data;
    const download=await request('/assets/'+file.id);assert.equal(download.headers.get('content-type'),'image/png');
    assert.deepEqual(Buffer.from(await download.arrayBuffer()),bytes);
    const forged=new FormData();forged.set('file',new Blob(['<script>alert(1)</script>'],{type:'image/png'}),'forged.png');
    await assert.rejects(request('/files',{method:'POST',body:forged}),/Formato/);
    await db.query('UPDATE built_legacy.directus_files SET filename_disk=$1 WHERE id=$2',['../outside',file.id]);
    await assert.rejects(request('/assets/'+file.id),/Armazenamento/);
    await db.query('UPDATE built_legacy.directus_files SET filename_disk=$1 WHERE id=$2',[file.filename_disk,file.id]);
    await request('/files/'+file.id,{method:'DELETE'});
    assert.deepEqual(await readFile(path.join(root,file.filename_disk)),bytes);
    await assert.rejects(request('/assets/'+file.id),/não encontrado/);
  }finally{await db.close();for(const name of await readdir(root))await unlink(path.join(root,name));await rmdir(root);}
});
test('native: homologação exige segredo próprio e não admite credenciais externas',()=>{
  const keys=['BUILT_ISOLATED_STAGE','BUILT_DATA_BACKEND','SESSION_SECRET','SMTP_PASS','SMTP_USER','DIRECTUS_TOKEN','ASAAS_API_KEY','OPENAI_API_KEY','STRIPE_SECRET_KEY','GOOGLE_CLIENT_SECRET'];
  const original=Object.fromEntries(keys.map(key=>[key,process.env[key]]));
  try{
    for(const key of keys)delete process.env[key];
    process.env.BUILT_ISOLATED_STAGE='1';
    assert.throws(assertIsolatedStageEnvironment,/segredo/);
    process.env.BUILT_DATA_BACKEND='postgres';process.env.SESSION_SECRET='test-only'.repeat(8);
    assert.doesNotThrow(assertIsolatedStageEnvironment);
    process.env.SMTP_PASS='fixture-only';
    assert.throws(assertIsolatedStageEnvironment,/credenciais/);
  }finally{for(const key of keys)if(original[key]===undefined)delete process.env[key];else process.env[key]=original[key];}
});
test('native: login importado valida hash e status, ticket curto não reutilizável',async()=>{
  const {db,catalog}=await fixture();try{
    await db.query('INSERT INTO built_legacy.directus_users(id,email,password,status) VALUES($1,$2,$3,$4)',['test','test@example.test',await hash('fixture-only-password'),'active']);
    const request=(pathname:string,init?:RequestInit)=>nativeRequest(db,catalog,new URL('https://internal.invalid'+pathname),init);
    const login=()=>request('/auth/login',{method:'POST',body:JSON.stringify({email:'test@example.test',password:'fixture-only-password'})});
    const result=await login();assert.equal(result.status,200);
    const token=(await result.json()).data.access_token;
    const headers={Authorization:'Bearer '+token};
    const me=await request('/users/me',{headers});assert.equal(me.status,200);assert.ok(!JSON.stringify(await me.json()).includes('password'));
    assert.equal((await request('/users/me',{headers})).status,401);
    await db.exec("UPDATE built_legacy.directus_users SET status='suspended'");
    assert.equal((await login()).status,401);
    await db.exec("UPDATE built_legacy.directus_users SET status='active',tfa_secret='fixture-mfa'");
    assert.equal((await login()).status,401);
  }finally{await db.close();}
});
